/**
 * BreakerMED — a tracker for ICEBREAKER that works like OctaMED and
 * ProTracker: blocks of tracks, one line a step, notes + instrument + hex
 * commands, a play sequence. It reads and writes .bmed (its own), .med
 * (MMD0–MMD3) and .mod.
 *
 * It runs in the deck's sandbox: its sound goes through ib.audio (permission
 * "audio"), its files through ib.vault, read and write in songs/ only
 * ("vault:read:songs/", "vault:write:songs/"), its notes through "notify".
 *
 *   src/song.ts         what a song is (one model for .bmed, .med and .mod)
 *   src/format/         the readers and the writers
 *   src/replayer.ts     the song, tick by tick
 *   src/engine.ts       the replayer, ahead of the sound, into ib.audio
 *   src/app.ts          the page · src/commands.ts the `med` command · src/keys.ts the piano
 *
 * Built into one readable main.js: `node modules/breakermed/build.mjs`.
 */
import type { IcebreakerAPI } from "./icebreaker";
import { makeApp, newState, type State } from "./app";
import { registerCommands } from "./commands";
import { Engine } from "./engine";
import { Autosave } from "./autosave";

let engine: Engine | null = null;

export function activate(ib: IcebreakerAPI): void {
  // the deck's sampler came after 0.5.0: say so plainly on an older deck
  if (!ib.audio || typeof ib.audio.schedule !== "function") throw new Error("BreakerMED needs a newer ICEBREAKER (one with ib.audio, the modules' sound): update the deck");
  ib.lib.addTranslations("fr", FR);
  engine = new Engine(ib.audio);
  const st: State = newState();
  // the autosave: a copy in songs/.recovery/ after each change (autosave.ts)
  st.autosave = new Autosave(
    { vault: ib.vault, storage: ib.storage, now: () => Date.now(), later: (fn, ms) => setTimeout(fn, ms), cancel: (h) => clearTimeout(h as ReturnType<typeof setTimeout>) },
    () => ({ song: st.song, editor: st.editor, path: st.path, playing: !!engine?.playing }),
  );
  st.autosave.onError = (m) => ib.ui.notify(`autosave off — ${m} (med autosave on to try again)`, "warning");
  void st.autosave.load().then(() => ib.ui.redraw());
  engine.onChange = () => ib.ui.redraw();
  // you silence it from the deck (`audio stop`, the ♪ in the status bar): the song stops, not only its notes
  ib.audio.onStop?.(() => engine?.silence());
  void ib.storage.get("paula", true).then((v) => engine && (engine.paula = v !== false));
  // the page's own settings (med view, med follow, med click)
  void ib.storage.get("view", "center").then((v) => (st.view = v === "edges" ? "edges" : "center"));
  void ib.storage.get("follow", true).then((v) => (st.follow = v !== false));
  void ib.storage.get("metronome", false).then((v) => engine && (engine.metronome = st.metronome = v === true));

  registerCommands(ib, engine, st);
  ib.apps.register({
    kind: "breakermed",
    title: "BreakerMED (beta)",
    description: "a tracker: .bmed, .med and .mod songs, played and edited",
    icon: "♫",
    launcher: true,
    // the keyboard is a piano here: every key comes with its place (KeyZ…), never as text
    rawKeys: true,
    create: () => makeApp(ib, engine!, st),
  });
  ib.palette.register({ id: "breakermed.open", title: "BreakerMED: open a song…", run: () => void ib.shell.run("med open") });
  ib.palette.register({ id: "breakermed.stop", title: "BreakerMED: stop", run: () => void ib.shell.run("med stop") });
  ib.palette.register({ id: "breakermed.new", title: "BreakerMED: a new song", run: () => void ib.shell.run("med new") });
  ib.palette.register({ id: "breakermed.demo", title: "BreakerMED: the demo song", run: () => void ib.shell.run("med demo") });
  ib.palette.register({ id: "breakermed.save", title: "BreakerMED: save the song", run: () => void ib.shell.run("med save") });
  ib.palette.register({ id: "breakermed.export", title: "BreakerMED: export (WAV, 24 bits) and the tracks apart", run: () => void ib.shell.run("med export --stems") });
}

export function deactivate(): void {
  engine?.stop();
  engine = null;
}

